import pg from 'pg';

const { Client } = pg;

const client = new Client({
  connectionString: process.env.DATABASE_URL,
  ssl: {
    rejectUnauthorized: false
  }
});

const sql = `

-- =========================================================
-- PROJECT WAREHOUSE - COMPLETE DATABASE SCHEMA
-- =========================================================

-- 1. EMPLOYEE ID SEQUENCE
CREATE SEQUENCE IF NOT EXISTS emp_id_seq;

-- 2. USERS TABLE
CREATE TABLE IF NOT EXISTS users (
    user_id TEXT PRIMARY KEY,
    emp_id TEXT NOT NULL UNIQUE
        DEFAULT ('EMP' || lpad(nextval('emp_id_seq')::text, 3, '0')),
    user_name TEXT NOT NULL,
    mobile TEXT,
    password_hash TEXT,
    email TEXT NOT NULL UNIQUE,
    user_type TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    active_session_id UUID,
    date_of_joining DATE,
    CONSTRAINT users_user_type_check
        CHECK (user_type IN ('Administrator', 'User'))
);

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS password_hash TEXT;

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS active_session_id UUID;

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS date_of_joining DATE;

ALTER TABLE users
    ALTER COLUMN emp_id SET DEFAULT
    ('EMP' || lpad(nextval('emp_id_seq')::text, 3, '0'));

SELECT setval(
    'emp_id_seq',
    COALESCE(
        (
            SELECT MAX(
                NULLIF(
                    regexp_replace(emp_id, '[^0-9]', '', 'g'),
                    ''
                )::BIGINT
            )
            FROM users
        ),
        0
    ) + 1,
    false
);

-- 3. PERMISSIONS TABLE
CREATE TABLE IF NOT EXISTS permissions (
    permission_code TEXT PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. USER PERMISSIONS MAPPING
CREATE TABLE IF NOT EXISTS user_permissions (
    user_id TEXT NOT NULL,
    permission_code TEXT NOT NULL,
    assigned_on TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (user_id, permission_code),

    CONSTRAINT user_permissions_user_fk
        FOREIGN KEY (user_id)
        REFERENCES users (user_id)
        ON DELETE CASCADE,

    CONSTRAINT user_permissions_permission_fk
        FOREIGN KEY (permission_code)
        REFERENCES permissions (permission_code)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_user_permissions_permission_code
    ON user_permissions (permission_code);

-- 5. PROJECTS TABLE
CREATE TABLE IF NOT EXISTS projects (
    project_id TEXT PRIMARY KEY,
    project_name TEXT NOT NULL,
    project_status TEXT NOT NULL DEFAULT 'Active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT projects_project_name_not_blank
        CHECK (length(btrim(project_name)) > 0)
);

-- 6. PROJECT USER MAPPING
CREATE TABLE IF NOT EXISTS project_user_mapping (
    uni_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    assigned_on TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT project_user_mapping_project_fk
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id)
        ON DELETE CASCADE,

    CONSTRAINT project_user_mapping_user_fk
        FOREIGN KEY (user_id)
        REFERENCES users (user_id)
        ON DELETE CASCADE,

    CONSTRAINT project_user_mapping_project_user_unique
        UNIQUE (project_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_project_user_mapping_user_id
    ON project_user_mapping (user_id);

-- 7. TASK MASTER
CREATE TABLE IF NOT EXISTS task_master (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_name VARCHAR(100) NOT NULL,
    status VARCHAR(1) NOT NULL DEFAULT 'A',

    CONSTRAINT task_master_task_name_not_blank
        CHECK (length(btrim(task_name)) > 0)
);

-- 8. TASK USER MAPPING
CREATE TABLE IF NOT EXISTS task_user_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid BIGINT NOT NULL,
    project_id TEXT NOT NULL,
    description TEXT,
    status VARCHAR(50),
    reference_link TEXT,
    reference_document TEXT,
    assigned_to VARCHAR(100),
    assigned_on DATE,

    CONSTRAINT task_user_mapping_task_fk
        FOREIGN KEY (pid)
        REFERENCES task_master (task_id),

    CONSTRAINT task_user_mapping_project_fk
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id)
        ON DELETE CASCADE
);

ALTER TABLE task_user_mapping
    ADD COLUMN IF NOT EXISTS project_id TEXT;

CREATE INDEX IF NOT EXISTS idx_task_user_mapping_pid
    ON task_user_mapping (pid);

CREATE INDEX IF NOT EXISTS idx_task_user_mapping_assigned_to
    ON task_user_mapping (assigned_to);

CREATE INDEX IF NOT EXISTS idx_task_user_mapping_project_id
    ON task_user_mapping (project_id);

-- 9. PROJECT FOLDERS
CREATE TABLE IF NOT EXISTS project_folders (
    folder_id VARCHAR(150) PRIMARY KEY,
    project_id VARCHAR(150) NOT NULL,
    parent_folder_id VARCHAR(150),
    folder_name VARCHAR(255) NOT NULL,
    created_by VARCHAR(150),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_project_folder_project
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_project_folder_parent
        FOREIGN KEY (parent_folder_id)
        REFERENCES project_folders (folder_id)
        ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_project_folder_name
    ON project_folders (
        project_id,
        COALESCE(parent_folder_id, ''),
        folder_name
    );

-- 10. PROJECT FILES
CREATE TABLE IF NOT EXISTS project_files (
    id VARCHAR(150) PRIMARY KEY,
    project_id VARCHAR(150) NOT NULL,
    folder_id VARCHAR(150) NOT NULL,
    file_name VARCHAR(500) NOT NULL,
    blob_name VARCHAR(1000) NOT NULL,
    file_type VARCHAR(100),
    content_type VARCHAR(255),
    file_size BIGINT NOT NULL,
    uploaded_by VARCHAR(150),
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_project_file_project
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_project_file_folder
        FOREIGN KEY (folder_id)
        REFERENCES project_folders (folder_id)
        ON DELETE CASCADE
);

-- 11. OTP CHALLENGES
CREATE TABLE IF NOT EXISTS otp_challenges (
    challenge_id UUID PRIMARY KEY,
    user_id TEXT NOT NULL
        REFERENCES users (user_id)
        ON DELETE CASCADE,
    otp_hash TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    resend_available_at TIMESTAMPTZ NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_otp_challenges_user_active
    ON otp_challenges (user_id, created_at DESC)
    WHERE consumed_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_otp_challenges_expiry
    ON otp_challenges (expires_at);

`;

async function main() {
  try {
    console.log('Connecting to PostgreSQL...');

    await client.connect();

    console.log('Connected successfully.');
    console.log('Creating Project Warehouse database schema...');

    await client.query('BEGIN');

    await client.query(sql);

    await client.query('COMMIT');

    console.log('');
    console.log('========================================');
    console.log('ALL TABLES CREATED SUCCESSFULLY');
    console.log('========================================');

  } catch (error) {
    console.error('');
    console.error('========================================');
    console.error('DATABASE SCHEMA CREATION FAILED');
    console.error('========================================');
    console.error(error);

    try {
      await client.query('ROLLBACK');
    } catch (_) {
      // Ignore rollback error
    }

    process.exitCode = 1;

  } finally {
    await client.end();
  }
}

main();